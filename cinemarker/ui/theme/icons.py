_icon_cache: dict[tuple, QIcon] = {}
_pix_cache: dict[tuple, QPixmap] = {}


def svg(name: str) -> str:
    body = _BODIES.get(name)
    if body is None:
        raise KeyError(f"Onbekend icoon: {name!r}")
    return _HEAD + body + "</svg>"


def _dpr() -> float:
    screen = QGuiApplication.primaryScreen()
    return screen.devicePixelRatio() if screen else 1.0


def pixmap(name: str, size: int = T.ICON_SIZE, color: str = T.TEXT_MUTED,
           dpr: float | None = None) -> QPixmap:
    """Eén gekleurde pixmap (voor delegates die zelf tekenen)."""
    dpr = dpr or _dpr()
    key = (name, size, color, dpr)
    pm = _pix_cache.get(key)
    if pm is None:
        px = int(round(size * dpr))
        pm = QPixmap(px, px)
        pm.fill(Qt.GlobalColor.transparent)
        renderer = QSvgRenderer(QByteArray(svg(name).replace("currentColor", color).encode("utf-8")))
        painter = QPainter(pm)
        painter.setRenderHint(QPainter.RenderHint.Antialiasing)
        renderer.render(painter)
        painter.end()
        pm.setDevicePixelRatio(dpr)
        _pix_cache[key] = pm
    return pm


def icon(name: str, size: int = T.ICON_SIZE, color: str | None = None) -> QIcon:
    """QIcon met state-kleuren. Met `color` krijgt elke state die ene kleur
    (voor gekleurde actieknoppen zoals rood 'verwijderen')."""
    dpr = _dpr()
    key = (name, size, color, dpr)
    ic = _icon_cache.get(key)
    if ic is None:
        ic = QIcon()
        for (mode, state), tok in _STATE_COLORS.items():
            use = color if (color and mode != QIcon.Mode.Disabled) else tok
            ic.addPixmap(pixmap(name, size, use, dpr), mode, state)
        _icon_cache[key] = ic
    return ic


def tinted(name: str, size: int, normal: str, hover: str | None = None,
           checked: str | None = None) -> QIcon:
    """QIcon met expliciete kleuren per toestand."""
    dpr = _dpr()
    key = ("tinted", name, size, normal, hover, checked, dpr)
    ic = _icon_cache.get(key)
    if ic is None:
        ic = QIcon()
        hov = hover or normal
        chk = checked or T.ACCENT
        ic.addPixmap(pixmap(name, size, normal, dpr), QIcon.Mode.Normal, QIcon.State.Off)
        ic.addPixmap(pixmap(name, size, hov, dpr), QIcon.Mode.Active, QIcon.State.Off)
        ic.addPixmap(pixmap(name, size, hov, dpr), QIcon.Mode.Selected, QIcon.State.Off)
        ic.addPixmap(pixmap(name, size, T.TEXT_DIM, dpr), QIcon.Mode.Disabled, QIcon.State.Off)
        ic.addPixmap(pixmap(name, size, chk, dpr), QIcon.Mode.Normal, QIcon.State.On)
        ic.addPixmap(pixmap(name, size, chk, dpr), QIcon.Mode.Active, QIcon.State.On)
        ic.addPixmap(pixmap(name, size, chk, dpr), QIcon.Mode.Selected, QIcon.State.On)
        _icon_cache[key] = ic
    return ic


def file_icon(path: str, size: int = T.ICON_SIZE) -> QIcon | None:
    """Icoon uit een afbeeldingsbestand (categorie-iconen), None als onleesbaar."""
    pm = QPixmap(path)
    if pm.isNull():
        return None
    return QIcon(pm.scaled(QSize(size, size), Qt.AspectRatioMode.KeepAspectRatio,
                           Qt.TransformationMode.SmoothTransformation))


def qcolor(hex_or_rgba: str | tuple) -> QColor:
    if isinstance(hex_or_rgba, tuple):
        return QColor(*hex_or_rgba)
    return QColor(hex_or_rgba)
